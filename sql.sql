CREATE TABLE RG_GAME (
    GAME_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CODE VARCHAR2(50 CHAR) NOT NULL,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    GAME_MODE VARCHAR2(20 CHAR) NOT NULL,
    MIN_PLAYERS NUMBER(3) NOT NULL,
    MAX_PLAYERS NUMBER(3) NOT NULL,
    HAS_ROUNDS NUMBER(1) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_RG_GAME PRIMARY KEY (GAME_ID),
    CONSTRAINT UQ_RG_GAME_CODE UNIQUE (CODE)
);


ALTER TABLE RG_GAME ADD (
    CONSTRAINT CK_RG_GAME_MODE
        CHECK (GAME_MODE IN ('SOLO', 'MULTIPLAYER')),

    CONSTRAINT CK_RG_GAME_MIN_PLAYERS
