CREATE TABLE RG_MATCH (
    MATCH_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    GAME_ID NUMBER(19)
        NOT NULL,

    STATUS VARCHAR2(20 CHAR)
        NOT NULL,

    CREATED_AT TIMESTAMP
        DEFAULT SYSTIMESTAMP
        NOT NULL,

    STARTED_AT TIMESTAMP,

    ENDED_AT TIMESTAMP,

    CONSTRAINT PK_RG_MATCH
        PRIMARY KEY (MATCH_ID),

    CONSTRAINT FK_RG_MATCH_GAME
        FOREIGN KEY (GAME_ID)
        REFERENCES RG_GAME (GAME_ID),

    CONSTRAINT CK_RG_MATCH_STATUS
        CHECK (
            STATUS IN (
                'WAITING',
                'RUNNING',
                'FINISHED',
                'ABORTED'
            )
        ),

    CONSTRAINT CK_RG_MATCH_DATES
        CHECK (
            (STARTED_AT IS NULL AND ENDED_AT IS NULL)
            OR
            (STARTED_AT IS NOT NULL AND ENDED_AT IS NULL)
            OR
            (STARTED_AT IS NOT NULL AND ENDED_AT IS NOT NULL)
        ),

    CONSTRAINT CK_RG_MATCH_STATUS_DATES
        CHECK (
            (STATUS = 'WAITING'
                AND STARTED_AT IS NULL
                AND ENDED_AT IS NULL)

            OR

            (STATUS = 'RUNNING'
                AND STARTED_AT IS NOT NULL
                AND ENDED_AT IS NULL)

            OR

            (STATUS IN ('FINISHED', 'ABORTED')
                AND STARTED_AT IS NOT NULL
                AND ENDED_AT IS NOT NULL)
        )
);


SELECT
    CONSTRAINT_NAME,
    CONSTRAINT_TYPE,
    SEARCH_CONDITION,
    STATUS
FROM USER_CONSTRAINTS
WHERE TABLE_NAME = 'RG_MATCH'
ORDER BY CONSTRAINT_TYPE, CONSTRAINT_NAME;






CREATE TABLE RG_MATCH_PLAYER (
    MATCH_PLAYER_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    MATCH_ID NUMBER(19)
        NOT NULL,

    USER_ID NUMBER(19)
        NOT NULL,

    FINAL_SCORE NUMBER(12, 2),

    POSITION NUMBER(3),

    CONSTRAINT PK_RG_MATCH_PLAYER
        PRIMARY KEY (MATCH_PLAYER_ID),

    CONSTRAINT FK_RG_MP_MATCH
        FOREIGN KEY (MATCH_ID)
        REFERENCES RG_MATCH (MATCH_ID),

    CONSTRAINT FK_RG_MP_USER
        FOREIGN KEY (USER_ID)
        REFERENCES RG_USER (USER_ID),

    CONSTRAINT UQ_RG_MP_MATCH_USER
        UNIQUE (MATCH_ID, USER_ID),

    CONSTRAINT UQ_RG_MP_ID_MATCH
        UNIQUE (MATCH_PLAYER_ID, MATCH_ID),

    CONSTRAINT CK_RG_MP_POSITION
        CHECK (POSITION IS NULL OR POSITION >= 1)
);






CREATE TABLE RG_MATCH_ROUND (
    MATCH_ROUND_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    MATCH_ID NUMBER(19)
        NOT NULL,

    ROUND_NUMBER NUMBER(5)
        NOT NULL,

    STATUS VARCHAR2(20 CHAR)
        NOT NULL,

    STARTED_AT TIMESTAMP
        NOT NULL,

    ENDED_AT TIMESTAMP,

    CONSTRAINT PK_RG_MATCH_ROUND
        PRIMARY KEY (MATCH_ROUND_ID),

    CONSTRAINT FK_RG_MR_MATCH
        FOREIGN KEY (MATCH_ID)
        REFERENCES RG_MATCH (MATCH_ID),

    CONSTRAINT UQ_RG_MR_NUMBER
        UNIQUE (MATCH_ID, ROUND_NUMBER),

    CONSTRAINT UQ_RG_MR_ID_MATCH
        UNIQUE (MATCH_ROUND_ID, MATCH_ID),

    CONSTRAINT CK_RG_MR_NUMBER
        CHECK (ROUND_NUMBER >= 1),

    CONSTRAINT CK_RG_MR_STATUS
        CHECK (
            STATUS IN ('RUNNING', 'FINISHED', 'ABORTED')
        ),

    CONSTRAINT CK_RG_MR_DATES
        CHECK (
            ENDED_AT IS NULL
            OR ENDED_AT >= STARTED_AT
        ),

    CONSTRAINT CK_RG_MR_STATUS_DATES
        CHECK (
            (STATUS = 'RUNNING' AND ENDED_AT IS NULL)
            OR
            (STATUS IN ('FINISHED', 'ABORTED')
                AND ENDED_AT IS NOT NULL)
        )
);






CREATE TABLE RG_MATCH_PLAYER_ROUND (
    MATCH_PLAYER_ROUND_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    MATCH_ID NUMBER(19)
        NOT NULL,

    MATCH_ROUND_ID NUMBER(19)
        NOT NULL,

    MATCH_PLAYER_ID NUMBER(19)
        NOT NULL,

    SCORE NUMBER(12, 2),

    CONSTRAINT PK_RG_MATCH_PLAYER_ROUND
        PRIMARY KEY (MATCH_PLAYER_ROUND_ID),

    CONSTRAINT FK_RG_MPR_ROUND
        FOREIGN KEY (MATCH_ROUND_ID, MATCH_ID)
        REFERENCES RG_MATCH_ROUND (MATCH_ROUND_ID, MATCH_ID),

    CONSTRAINT FK_RG_MPR_PLAYER
        FOREIGN KEY (MATCH_PLAYER_ID, MATCH_ID)
        REFERENCES RG_MATCH_PLAYER (MATCH_PLAYER_ID, MATCH_ID),

    CONSTRAINT UQ_RG_MPR_ROUND_PLAYER
        UNIQUE (MATCH_ROUND_ID, MATCH_PLAYER_ID)
);






CREATE TABLE RG_ASSET (
    ASSET_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    ASSET_TYPE VARCHAR2(20 CHAR)
        NOT NULL,

    PATH VARCHAR2(500 CHAR)
        NOT NULL,

    FILENAME VARCHAR2(255 CHAR)
        NOT NULL,

    CONSTRAINT PK_RG_ASSET
        PRIMARY KEY (ASSET_ID),

    CONSTRAINT CK_RG_ASSET_TYPE
        CHECK (
            ASSET_TYPE IN (
                'IMAGE',
                'AUDIO',
                'VIDEO',
                'OTHER'
            )
        )
);






CREATE TABLE RG_CONTENT_ITEM (
