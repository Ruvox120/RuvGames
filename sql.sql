    CONSTRAINT CK_RG_GAME_MAX_PLAYERS
        CHECK (MAX_PLAYERS >= MIN_PLAYERS),

    CONSTRAINT CK_RG_GAME_HAS_ROUNDS
        CHECK (HAS_ROUNDS IN (0, 1)),

    CONSTRAINT CK_RG_GAME_ENABLED
        CHECK (ENABLED IN (0, 1))
);

